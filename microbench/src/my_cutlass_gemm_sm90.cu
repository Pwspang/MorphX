// Hopper-native (sm_90a) variant of libmycutlass.so: same C API as
// my_cutlass_gemm.cu (myCutlassHgemm, fp16 in/out, fp32 accumulate, every
// matrix column-major, D = alpha * A * B + beta * C with C == D, caller's stream),
// built from CUTLASS 3 WGMMA + TMA kernels instead of CUTLASS 2 Sm80 ones.
// Selected with -DMORPHX_MYCUTLASS_ARCH=sm90 (microbench/CMakeLists.txt).
//
// The MorphX pass turns every CTA into a persistent agent itself and needs an
// ordinary grid of independent CTAs with a 1x1x1 cluster. KernelTma (one
// consumer warpgroup) and KernelTmaWarpSpecialized (producer + consumer
// warpgroup) are non-persistent. The cooperative and ping-pong schedules are
// persistent; with hw_info.sm_count above the tile count their scheduler
// launches one CTA per output tile, which makes them ordinary grids too (up to
// 65535 CTAs). They
// also reconfigure registers per warpgroup (setmaxnreg), which then runs again
// for every logical block an agent executes; that works on the H200 (checked
// under the runtime with several logical blocks per agent).
//
// Configs are chosen per (m, n, k) from the table generated by
// microbench/src/sm90_select.py out of the sm90_tune results
// (my_cutlass_gemm_sm90_table.inc). myCutlassSm90Run() runs one config by
// index for that tuning.

// CUTLASS leaves __grid_constant__ off under clang; TMA descriptors must stay
// in param space, not in a local copy of Params.
#ifndef CUTLASS_GRID_CONSTANT
#define CUTLASS_GRID_CONSTANT __grid_constant__
#endif

