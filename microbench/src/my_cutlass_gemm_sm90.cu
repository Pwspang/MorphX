namespace my_cutlass_gemm_sm90 {

using namespace cute;
using Element = cutlass::half_t;
using Layout = cutlass::layout::ColumnMajor;
using StrideC = cutlass::detail::TagToStrideC_t<Layout>;

// KernelTma pairs with the register-only DefaultEpilogue, the warp-specialized
// kernel with the TMA epilogue (both as in CUTLASS example 49).
template <class TileShape, class Schedule>
struct EpilogueFor {
  using Op = cutlass::epilogue::collective::DefaultEpilogue<
      Element, StrideC, StrideC,
      cutlass::epilogue::thread::LinearCombination<Element, 1, float, float>,
      cutlass::gemm::EpilogueDefault>;
};
template <class TileShape, class EpiSchedule>
struct TmaEpilogue {
  using Op = typename cutlass::epilogue::collective::CollectiveBuilder<
      cutlass::arch::Sm90, cutlass::arch::OpClassTensorOp,
      TileShape, Shape<_1, _1, _1>, cutlass::epilogue::collective::EpilogueTileAuto,
      float, float,
      Element, Layout, 8,
      Element, Layout, 8,
      EpiSchedule>::CollectiveOp;
};
template <class TileShape>
struct EpilogueFor<TileShape, cutlass::gemm::KernelTmaWarpSpecialized>
    : TmaEpilogue<TileShape, cutlass::epilogue::TmaWarpSpecialized> {};
template <class TileShape>
struct EpilogueFor<TileShape, cutlass::gemm::KernelTmaWarpSpecializedPingpong>
    : TmaEpilogue<TileShape, cutlass::epilogue::TmaWarpSpecialized> {};
template <class TileShape>
struct EpilogueFor<TileShape, cutlass::gemm::KernelTmaWarpSpecializedCooperative>
    : TmaEpilogue<TileShape, cutlass::epilogue::TmaWarpSpecializedCooperative> {};

template <int TM, int TN, int TK, class Schedule>
struct Config {
  using TileShape = Shape<Int<TM>, Int<TN>, Int<TK>>;
  using CollectiveEpilogue = typename EpilogueFor<TileShape, Schedule>::Op;
  using CollectiveMainloop = typename cutlass::gemm::collective::CollectiveBuilder<
      cutlass::arch::Sm90, cutlass::arch::OpClassTensorOp,
      Element, Layout, 8,
      Element, Layout, 8,
      float, TileShape, Shape<_1, _1, _1>,
      cutlass::gemm::collective::StageCountAutoCarveout<
          static_cast<int>(sizeof(typename CollectiveEpilogue::SharedStorage))>,
      Schedule>::CollectiveOp;
  using GemmKernel = cutlass::gemm::kernel::GemmUniversal<
      Shape<int, int, int, int>, CollectiveMainloop, CollectiveEpilogue>;
  using Gemm = cutlass::gemm::device::GemmUniversalAdapter<GemmKernel>;

  // Returns false if CUTLASS can't run this problem (alignment).
  static bool run(int m, int n, int k, const Element *a, int64_t lda, const Element *b, int64_t ldb,
                  Element *c, int64_t ldc, float alpha, float beta, cudaStream_t stream) {
    // Leading dimensions as given (x may be a strided view): A is M-major,
    // B K-major, C/D M-major; batch stride unused (L = 1).
    auto sA = cutlass::make_cute_packed_stride(typename GemmKernel::StrideA{}, make_shape(m, k, 1));
    auto sB = cutlass::make_cute_packed_stride(typename GemmKernel::StrideB{}, make_shape(n, k, 1));
    auto sC = cutlass::make_cute_packed_stride(typename GemmKernel::StrideC{}, make_shape(m, n, 1));
    auto sD = cutlass::make_cute_packed_stride(typename GemmKernel::StrideD{}, make_shape(m, n, 1));
    get<1>(sA) = lda;
    get<0>(sB) = ldb;
    get<1>(sC) = ldc;
    get<1>(sD) = ldc;
    // Persistent schedulers launch min(tiles, sm_count) CTAs along one grid
    // dimension: one CTA per tile up to the 65535 limit of grid y (lm_head
    // prefill has more tiles; those CTAs then take a second tile).
    cutlass::KernelHardwareInfo hw_info;
    hw_info.sm_count = 65535;
    typename Gemm::Arguments args{
        cutlass::gemm::GemmUniversalMode::kGemm,
        {m, n, k, 1},
        {a, sA, b, sB},
        {{alpha, beta}, c, sC, c, sD},
        hw_info};
    if (Gemm::can_implement(args) != cutlass::Status::kSuccess) return false;
    // Once per config instead of in every initialize(): the opt-in for more
    // than 48 KB of dynamic shared memory.
    static const bool attr_set = [] {
      int smem = GemmKernel::SharedStorageSize;
      if (smem >= (48 << 10) &&
          cudaFuncSetAttribute(cutlass::device_kernel<GemmKernel>,
                               cudaFuncAttributeMaxDynamicSharedMemorySize, smem) != cudaSuccess)
        throw std::runtime_error("mycutlass sm90: cudaFuncSetAttribute failed");
      return true;
    }();
    (void)attr_set;
    if (Gemm::get_workspace_size(args) != 0)
      throw std::runtime_error("mycutlass sm90: kernel needs a workspace");
    auto params = GemmKernel::to_underlying_arguments(args, nullptr);
    if (Gemm::run(params, stream) != cutlass::Status::kSuccess)
      throw std::runtime_error("mycutlass sm90: kernel launch failed");
    return true;
  }
};

using Tma = cutlass::gemm::KernelTma;
using Ws = cutlass::gemm::KernelTmaWarpSpecialized;
using Coop = cutlass::gemm::KernelTmaWarpSpecializedCooperative;
using Pingpong = cutlass::gemm::KernelTmaWarpSpecializedPingpong;

using RunFn = bool (*)(int, int, int, const Element *, int64_t, const Element *, int64_t,
                       Element *, int64_t, float, float, cudaStream_t);
struct ConfigEntry {
  const char *name;
  RunFn run;
};

// Candidate set (tile M x N x K and schedule). Tile N runs along the token
// dimension (n = T): small N tiles keep more CTAs busy at decode batch sizes.
const ConfigEntry kConfigs[] = {
    {"tma_128x128x64", &Config<128, 128, 64, Tma>::run},
    {"ws_64x16x128", &Config<64, 16, 128, Ws>::run},
    {"ws_64x32x128", &Config<64, 32, 128, Ws>::run},
    {"ws_64x64x128", &Config<64, 64, 128, Ws>::run},
    {"ws_128x16x128", &Config<128, 16, 128, Ws>::run},
    {"ws_128x32x128", &Config<128, 32, 128, Ws>::run},
    {"ws_128x64x64", &Config<128, 64, 64, Ws>::run},
    {"ws_128x128x64", &Config<128, 128, 64, Ws>::run},
    {"coop_128x128x64", &Config<128, 128, 64, Coop>::run},
    {"coop_256x128x64", &Config<256, 128, 64, Coop>::run},
    {"coop_128x256x64", &Config<128, 256, 64, Coop>::run},
    {"pingpong_64x128x64", &Config<64, 128, 64, Pingpong>::run},
};
constexpr int kNumConfigs = sizeof(kConfigs) / sizeof(kConfigs[0]);

// Tuned choice per (m, k) and token count n <= n_max (sorted by n_max).
struct TableEntry {
  int m, k, n_max, config;
};
const TableEntry kTable[] = {
#include "my_cutlass_gemm_sm90_table.inc"
};
constexpr int kTableSize = sizeof(kTable) / sizeof(kTable[0]);

int select_config(int m, int n, int k) {
  // The tuned (m, k) closest in log space, then the first n bucket that holds n.
  double best = 1e30;
  int bm = 0, bk = 0;
  for (const TableEntry &e : kTable) {
    double d = std::fabs(std::log2((double)m / e.m)) + std::fabs(std::log2((double)k / e.k));
    if (d < best) { best = d; bm = e.m; bk = e.k; }
  }
  int last = -1;
  for (const TableEntry &e : kTable) {
    if (e.m != bm || e.k != bk) continue;
    last = e.config;
    if (n <= e.n_max) return e.config;
  }
  return last >= 0 ? last : 0;
}

}  // namespace my_cutlass_gemm_sm90

extern "C" void myCutlassHgemm(
    int m, int n, int k,
    const cutlass::half_t *a, long long int lda,
    const cutlass::half_t *b, long long int ldb,
    cutlass::half_t *c, long long int ldc,
    float alpha, float beta, cudaStream_t stream) {
  using namespace my_cutlass_gemm_sm90;
  int cfg = select_config(m, n, k);
  if (!kConfigs[cfg].run(m, n, k, a, lda, b, ldb, c, ldc, alpha, beta, stream))
    throw std::runtime_error("mycutlass sm90: problem not supported (alignment?)");
}

// Tuning hooks (not part of the mycutlass API).
extern "C" int myCutlassSm90NumConfigs() { return my_cutlass_gemm_sm90::kNumConfigs; }

extern "C" const char *myCutlassSm90ConfigName(int cfg) {
  using namespace my_cutlass_gemm_sm90;
  return cfg >= 0 && cfg < kNumConfigs ? kConfigs[cfg].name : nullptr;
}

extern "C" int myCutlassSm90SelectConfig(int m, int n, int k) {
  return my_cutlass_gemm_sm90::select_config(m, n, k);
}

// 0 = ran, 1 = problem not supported by this config.
extern "C" int myCutlassSm90Run(
    int cfg, int m, int n, int k,
    const cutlass::half_t *a, long long int lda,
    const cutlass::half_t *b, long long int ldb,
    cutlass::half_t *c, long long int ldc,
    float alpha, float beta, cudaStream_t stream) {
  using namespace my_cutlass_gemm_sm90;
  if (cfg < 0 || cfg >= kNumConfigs) return 1;
  return kConfigs[cfg].run(m, n, k, a, lda, b, ldb, c, ldc, alpha, beta, stream) ? 0 : 1;
}
