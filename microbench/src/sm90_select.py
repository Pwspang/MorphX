#!/usr/bin/env python3
"""Build the sm90 mycutlass selection table from gemm_libs_compare tune CSVs.

For every tuned (m, k) and token count n, pick the fastest config that passed,
then merge neighbouring n with the same choice into {m, k, n_max, config}
rows (n <= n_max; the last row of each (m, k) covers any larger n). Config
indices follow kConfigs in my_cutlass_gemm_sm90.cu, matched by name, so the
candidate list can be pruned and the table regenerated from the same CSVs.

  python3 microbench/src/sm90_select.py tune1.csv [tune2.csv ...] \
      > microbench/src/my_cutlass_gemm_sm90_table.inc
"""

import collections
import csv
import os
import re
import sys

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "my_cutlass_gemm_sm90.cu")


def config_indices():
    text = open(SRC).read()
    block = text[text.index("const ConfigEntry kConfigs[] = {"):]
    block = block[:block.index("};")]
    return {name: i for i, name in enumerate(re.findall(r'\{"([^"]+)"', block))}


def main(paths):
    index = config_indices()
    best = {}  # (m, k, n) -> (ms, name)
    for path in paths:
        with open(path) as f:
            for row in csv.DictReader(line for line in f if line[0].isdigit() or line.startswith("m,")):
                if row["status"] != "PASS" or row["name"] not in index:
                    continue
                key = (int(row["m"]), int(row["k"]), int(row["n"]))
                ms = float(row["ms"])
                if key not in best or ms < best[key][0]:
                    best[key] = (ms, row["name"])
    by_mk = collections.defaultdict(list)
    for (m, k, n), (ms, name) in best.items():
        by_mk[(m, k)].append((n, name))
    used = collections.Counter()
    print("// Generated by microbench/src/sm90_select.py from: " + " ".join(os.path.basename(p) for p in paths))
    print("// {m, k, n_max, config}: fastest config for n <= n_max (last row: any n)")
    for (m, k) in sorted(by_mk):
        rows = sorted(by_mk[(m, k)])
        merged = []
        for n, name in rows:
            if merged and merged[-1][1] == name:
                merged[-1] = (n, name)
            else:
                merged.append((n, name))
        for i, (n, name) in enumerate(merged):
            n_max = "1 << 30" if i == len(merged) - 1 else str(n)
            used[name] += 1
            print(f"{{{m}, {k}, {n_max}, {index[name]}}},  // {name}")
    print("// configs used: " + ", ".join(f"{n} x{c}" for n, c in sorted(used.items())), file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1:])
